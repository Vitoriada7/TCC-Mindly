CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    apelido VARCHAR(30) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    data_nascimento DATE NOT NULL,
    data_criacao TIMESTAMP(6) NOT NULL,
    ativo BOOLEAN NOT NULL,
    tema_escuro BOOLEAN,
    avatar VARCHAR(255)
);
CREATE TABLE usuario_avatar (
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    avatar VARCHAR(255) NOT NULL,
    PRIMARY KEY (usuario_id, avatar)
);
CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id)
);
CREATE TABLE tarefas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL,
    descricao TEXT,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDENTE','EM_ANDAMENTO','CONCLUIDA')),
    prioridade VARCHAR(10) NOT NULL CHECK (prioridade IN ('BAIXA','MEDIA','ALTA')),
    data_criacao TIMESTAMP(6) NOT NULL,
    data_atualizacao TIMESTAMP(6) NOT NULL,
    data_limite TIMESTAMP(6),
    data_conclusao TIMESTAMP(6),
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    categoria_id BIGINT NOT NULL REFERENCES categorias(id)
);
CREATE TABLE habitos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    icone VARCHAR(50) NOT NULL,
    cor VARCHAR(30) NOT NULL,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    data_criacao TIMESTAMP(6) NOT NULL,
    ativo BOOLEAN NOT NULL
);
CREATE TABLE registros_habitos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    habito_id BIGINT NOT NULL REFERENCES habitos(id),
    data DATE NOT NULL,
    concluido BOOLEAN NOT NULL,
    CONSTRAINT uk_registro_habito_data UNIQUE (habito_id, data)
);
CREATE TABLE registros_emocionais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sentimento VARCHAR(40) NOT NULL,
    sentimento_detalhado VARCHAR(60),
    pensamento TEXT,
    exploracoes TEXT,
    reflexao TEXT,
    complemento_final TEXT,
    data_registro TIMESTAMP(6) NOT NULL,
    data DATE NOT NULL,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    CONSTRAINT uk_registro_emocional_usuario_data UNIQUE (usuario_id, data)
);
CREATE INDEX idx_registro_emocional_usuario_data ON registros_emocionais (usuario_id, data);
CREATE TABLE contatos_emergencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    telefone VARCHAR(20) NOT NULL,
    relacionamento VARCHAR(50),
    principal BOOLEAN NOT NULL,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id)
);
CREATE TABLE conexoes_google (
    usuario_id BIGINT PRIMARY KEY,
    refresh_token_cifrado VARCHAR(2000),
    estado_hash VARCHAR(255),
    estado_expira TIMESTAMP(6) WITH TIME ZONE,
    lista_id VARCHAR(500),
    ultima_sincronizacao TIMESTAMP(6) WITH TIME ZONE
);
CREATE TABLE tarefas_google (
    usuario_id BIGINT NOT NULL REFERENCES conexoes_google(usuario_id),
    tarefa_id BIGINT NOT NULL,
    google_id VARCHAR(500),
    PRIMARY KEY (usuario_id, tarefa_id)
);
